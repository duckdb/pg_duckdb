import pytest

from .utils import Cursor


@pytest.mark.parametrize("column_type", ["text", "varchar"])
def test_text_join_filter_collation(cur: Cursor, column_type):
    cur.sql("SET duckdb.force_execution = false")
    if not cur.sql("SELECT EXISTS (SELECT FROM pg_collation WHERE collprovider = 'i')"):
        pytest.skip("Postgres was built without ICU collations")

    cur.sql("CREATE COLLATION scan_order (provider = icu, locale = 'en')")
    cur.sql(f'CREATE TABLE build_keys ("join key" {column_type} COLLATE scan_order)')
    cur.sql(
        "INSERT INTO build_keys SELECT prefix || n "
        "FROM (VALUES ('Z'), ('a')) prefixes(prefix), generate_series(0, 9) n"
    )
    cur.sql("INSERT INTO build_keys VALUES (NULL)")
    cur.sql('CREATE TABLE probe_keys AS SELECT "join key" FROM build_keys')
    cur.sql(
        "INSERT INTO probe_keys SELECT prefix || n "
        "FROM (VALUES ('A'), ('z')) prefixes(prefix), generate_series(0, 9) n"
    )
    cur.sql("ANALYZE build_keys, probe_keys")

    # The byte-order bounds Z0..a9 are reversed in this collation. Applying
    # them in Postgres discards every matching row before DuckDB can join it.
    assert cur.sql("SELECT 'Z0' COLLATE scan_order > 'a9' COLLATE scan_order")
    queries = [
        ('SELECT count(*) FROM probe_keys p JOIN build_keys b USING ("join key")', 20),
        (
            'SELECT count(*) FROM probe_keys p WHERE "join key" IN '
            '(SELECT "join key" FROM build_keys)',
            20,
        ),
        (
            "SELECT count(*) FROM probe_keys p LEFT JOIN build_keys b "
            'USING ("join key") WHERE b."join key" IS NOT NULL',
            20,
        ),
    ]
    for query, expected in queries:
        assert cur.sql(query) == expected

    cur.sql("SET duckdb.force_execution = true")
    for query, expected in queries:
        assert cur.sql(query) == expected

    # Only optional bounds generated by DuckDB need byte ordering. Keep the
    # existing Postgres collation for mandatory filters from the user's SQL.
    assert (
        cur.sql(
            "SELECT count(*) FROM probe_keys WHERE \"join key\" >= 'Z0' "
            "AND \"join key\" <= 'a9'"
        )
        == 0
    )
